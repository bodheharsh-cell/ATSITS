"""Journal entry models preserving separation between system facts and qualitative notes."""

from datetime import datetime
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field
from atsits.models.types import FrozenMapping


class JournalEntry(BaseModel):
    """Represents a journal entry with strict separation of facts and interpretation.

    - system_facts: Deterministic, immutable data generated by the core trading engine.
    - gemini_notes: Optional qualitative interpretation or research observations.
    Gemini notes must never overwrite or mutate system facts.
    """

    model_config = ConfigDict(frozen=True, arbitrary_types_allowed=True)

    entry_id: str = Field(..., min_length=1, description="Unique identifier for the journal entry")
    timestamp: datetime = Field(..., description="Creation timestamp")
    event_type: str = Field(..., min_length=1, description="Event type (e.g. TRADE_FILLED, SETUP_REJECTED)")
    system_facts: FrozenMapping = Field(
        ...,
        description="Immutable deterministic execution facts from the trading engine",
    )
    gemini_notes: Optional[str] = Field(
        default=None,
        description="Optional qualitative analysis or notes from Gemini",
    )
